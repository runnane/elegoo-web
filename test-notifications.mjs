import assert from 'node:assert/strict';
import { MqttBridge } from './src/server/mqtt-bridge.ts';
import { TelegramIntegration } from './src/server/telegram.ts';
const bridge = new MqttBridge('127.0.0.1', '', 'TEST');
for (const method of ['stopRegisterRetry', 'stopSlowRegisterRetry', 'stopSilenceWatch', 'subscribeAll', 'startHeartbeat', 'sendCommand']) bridge[method] = () => {};
let count = 0;
bridge.on('connected', () => count++);
const reply = (topic, data) => bridge.handleMessage(topic, Buffer.from(JSON.stringify(data)));
reply('elegoo/TEST/other/register_response', {error:'ok'});
assert.equal(bridge.isConnected, false);
reply('elegoo/TEST/other/register_response', {code:3});
assert.equal(bridge._rejected, false);
const own = `elegoo/TEST/${bridge.requestId}/register_response`;
reply(own, {error:'ok'});
reply(own, {error:'ok'});
assert.equal(count, 1);
bridge._connected = false;
reply(own, {error:'ok'});
assert.equal(count, 2);
const telegram = Object.create(TelegramIntegration.prototype);
telegram.config = {telegramConnectionNotifications:false};
await telegram.handleEvent({type:'connected',sn:'TEST'});
await telegram.handleEvent({type:'disconnected'});
let sent = 0;
telegram.sendNew = async () => { sent++; return 1; };
await telegram.handleEvent({type:'print_started',filename:'synthetic.gcode',resumed:false});
assert.equal(sent, 1);
